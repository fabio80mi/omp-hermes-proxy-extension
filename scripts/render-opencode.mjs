/**
 * Render audit results as opencode provider blocks.
 *
 * opencode has no discovery mechanism, so this is a manual paste. Only models
 * that actually answered a tool call during the audit are emitted: a picker full
 * of models that fail on selection is worse than a short list that works.
 *
 * Models the audit excluded are listed as a trailing comment with the reason, so
 * the absence is explained rather than silent.
 */

import { toOpencodeModel } from "../src/providers.mjs";

export function renderOpencode(report) {
	const providers = {};
	const excluded = {};

	for (const provider of report.providers ?? []) {
		if (!provider.models?.length) continue;

		const usable = provider.models.filter((m) => m.state === "ok");
		if (usable.length === 0) continue;

		const models = {};
		for (const m of usable) models[m.id] = toOpencodeModel(m.wire);

		providers[`verified-${provider.id}`] = {
			npm: "@ai-sdk/openai-compatible",
			name: `${provider.label} (verified)`,
			options: { baseURL: String(provider.baseUrl ?? "").replace("localhost", "127.0.0.1") },
			models,
		};

		const skipped = provider.models.filter((m) => m.state !== "ok");
		if (skipped.length > 0) {
			excluded[`verified-${provider.id}`] = skipped.map(
				(m) => `      ${m.id}: ${m.state}${m.status ? ` (HTTP ${m.status})` : ""} — ${m.detail}`,
			);
		}
	}

	// Serialize once. Splicing JSON fragments together by hand reliably
	// produces a missing comma somewhere.
	const document = {
		$comment:
			"GENERATED by omp-hermes-proxy-extension from audit.json. Copy a provider block into " +
			"~/.config/opencode/opencode.jsonc. Only models that answered a real tool call during " +
			"the audit are listed. Regenerate with: node scripts/audit-models.mjs",
		generatedAt: report.generatedAt,
		provider: providers,
	};

	let text = `${JSON.stringify(document, null, 2)}\n`;

	const notes = Object.entries(excluded);
	if (notes.length > 0) {
		text += "\n/*\n * Excluded during the audit — reachable but not usable as an agent model.\n";
		for (const [id, lines] of notes) {
			text += ` *\n * ${id}:\n${lines.join("\n")}\n`;
		}
		text += " */\n";
	}
	return text;
}
