/**
 * Render audit results as opencode provider blocks.
 *
 * opencode has no discovery mechanism, so this is a manual paste.
 *
 * The picker set is emitted: `stable` models, plus `known-good` and `unstable`
 * ones that have worked at least once and have not been permanently broken.
 * A transient throttle or timeout never removes a model from here, because
 * churning the owner's opencode config on a busy afternoon breaks whatever
 * depends on it, and a model that worked once is still a model they can use.
 * Anything rejected, retired, or never successfully reached is listed in the
 * footer with the reason, so an absence is always explained. A picker full of models that fail on selection is worse than a short
 * list that works, and a single lucky pass is not evidence.
 *
 * Excluded models are listed as a trailing comment with the reason, so an
 * absence is explained rather than silent. Retirement is reported explicitly,
 * because the free catalogue changes over time and a model disappearing is
 * expected rather than a bug.
 */

import { toOpencodeModel } from "../src/providers.mjs";

export function renderOpencode(report, { stable = null, ids = null } = {}) {
	const providers = {};
	const excluded = {};

	// Index the stability verdict by "<provider>/<model>" so the renderer can say
	// why something is missing without re-deriving the rule.
	const stableById = new Map();
	for (const provider of stable?.providers ?? []) {
		for (const model of provider.models ?? []) {
			stableById.set(`${provider.id}/${model.id}`, model);
		}
	}

	for (const provider of report.providers ?? []) {
		if (!provider.models?.length) continue;

		const usable = provider.models.filter((m) => {
			// When a stability verdict is supplied it is the authority, and it
			// already accounts for history. Gating on this run's state as well
			// would drop a model that was throttled today but worked in an
			// earlier run — reintroducing exactly the churn the verdict exists
			// to prevent. Only fall back to this run's result with no history.
			if (ids) return ids.has(`${provider.id}/${m.id}`);
			return m.state === "ok";
		});
		if (usable.length === 0) continue;

		const models = {};
		for (const m of usable) models[m.id] = toOpencodeModel(m.wire);

		providers[`verified-${provider.id}`] = {
			npm: "@ai-sdk/openai-compatible",
			name: `${provider.label} (verified)`,
			options: { baseURL: String(provider.baseUrl ?? "").replace("localhost", "127.0.0.1") },
			models,
		};

		const skipped = [];
		for (const m of provider.models) {
			if (usable.includes(m)) continue;
			const verdict = stableById.get(`${provider.id}/${m.id}`);
			// A model that passed this run but lacks history is a different
			// situation from one that failed, and reads differently when it turns
			// up in the picker later.
			const state = verdict && verdict.status !== "stable" && m.state === "ok" ? verdict.status : m.state;
			const reason =
				verdict && verdict.status !== "stable" && m.state === "ok"
					? verdict.reason
					: m.detail;
			skipped.push(
				`      ${m.id}: ${state}${m.status ? ` (HTTP ${m.status})` : ""} — ${reason}`,
			);
		}

		// Retired models are not in this run's list at all, so they have to come
		// from the history verdict. Silence here would look like the model never
		// existed rather than one that stopped being free.
		for (const model of stable?.providers?.find((p) => p.id === provider.id)?.models ?? []) {
			if (model.status === "retired") {
				skipped.push(`      ${model.id}: retired — ${model.reason}`);
			}
		}

		if (skipped.length > 0) excluded[`verified-${provider.id}`] = skipped;
	}

	const document = {
		$comment:
			"GENERATED by omp-hermes-proxy-extension from audit-stable.json. Copy the provider blocks " +
			"into ~/.config/opencode/opencode.jsonc. A model is listed when it has worked at least once " +
			"and has not been permanently broken; throttles and timeouts never remove a model. " +
			"Regenerate with: node scripts/audit-models.mjs",
		generatedAt: stable?.generatedAt ?? report.generatedAt,
		rule: stable?.rule ?? null,
		provider: providers,
	};

	let text = `${JSON.stringify(document, null, 2)}\n`;

	const notes = Object.entries(excluded);
	if (notes.length > 0) {
		text += "\n/*\n * Not listed — never worked, or permanently gone. The free catalogue changes\n";
		text += " * over time; a model disappearing here is expected, not a bug.\n";
		for (const [id, lines] of notes) {
			text += ` *\n * ${id}:\n${lines.join("\n")}\n`;
		}
		text += " */\n";
	}
	return text;
}
