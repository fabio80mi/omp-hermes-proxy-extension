	apiKey: "HermesProxyLocal",
	fetchTimeoutMs: 5000,
	probeTimeoutMs: 30000,
	freeOnly: true,
	requireChat: true,
	requireTools: true,
	requireReasoning: false,
	maxContextWindow: 2_000_000,
	defaultMaxTokens: 8192,
	dedupeSnapshotVariants: true,
	verifyProbe: "free",
	probeConcurrency: 3,
	probeMaxTokens: 1,
	minModelsToAccept: 1,
