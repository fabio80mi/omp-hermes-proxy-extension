	"~/.config/opencode/opencode.jsonc. Only models that answered a real tool call during " +
	"the audit are listed. Regenerate with /hermes-refresh in OMP, or: node scripts/audit-models.mjs";

const THINKING_LEVELS = ["minimal", "low", "medium", "high", "xhigh", "max"] as const;

