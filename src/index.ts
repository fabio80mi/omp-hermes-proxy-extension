/**
 * Every provider this extension has registered, for the opencode export.
 *
 * Populated as each provider finishes loading rather than passed in, because the
 * additional providers load asynchronously and independently: the export has to
 * reflect whatever has actually registered, whenever that is.
 */
const OPENCODE_REGISTRY = new Map<string, { label: string; baseUrl: string; models: ProviderModelConfig[] }>();

/**
 * Render one provider's models as an `opencode.jsonc` block.
 *
 * Written for manual pasting: this extension never touches the user's opencode
 * config. opencode has no discovery mechanism comparable to OMP's, so the block
 * has to be copied in by hand.
 *
 * Field mapping differs from the OMP registration:
 *   limit.context / limit.output  <- context_length / top_provider.max_completion_tokens
 *   modalities.input               <- text and image only; opencode declares no
 *                                    video/audio/file input modality
 *   variants.<level>               <- one entry per advertised reasoning effort
 */
function renderProvider(
	models: ProviderModelConfig[],
	label: string,
	baseUrl: string,
): Record<string, unknown> {
	const entries: Record<string, unknown> = {};

	for (const model of models) {
		const wire = WIRE_BY_ID.get(model.id);
		const entry: Record<string, unknown> = {
			name: model.name,
			limit: { context: model.contextWindow, output: model.maxTokens },
			modalities: { input: [...model.input], output: ["text"] },
		};

		const efforts = wire?.reasoning?.supported_efforts;
		if (efforts && efforts.length > 0) {
			const variants: Record<string, unknown> = {};
			for (const level of THINKING_LEVELS) {
				if (efforts.includes(level)) variants[level] = { reasoningEffort: level };
			}
			// A model that advertises "none" can also run with reasoning disabled.
			if (efforts.includes("none") && !wire?.reasoning?.mandatory) {
				variants.none = { reasoningEffort: "none" };
			}
			if (Object.keys(variants).length > 0) entry.variants = variants;
		}

		entries[model.id] = entry;
	}

	return {
		npm: "@ai-sdk/openai-compatible",
		name: label,
		// opencode's openai-compatible provider sets the Authorization header from
		// apiKey itself, so no "Bearer " prefix here. Credentials are NOT written
		// to this file: the user supplies their own in opencode.jsonc.
		options: { baseURL: baseUrl.replace("localhost", "127.0.0.1") },
		models: entries,
	};
}

/**
 * A trailing JSONC comment listing what the audit excluded and why.
 *
 * This is the information people otherwise re-investigate by hand: a model that
 * is absent from the export is absent on purpose, not an oversight.
 */
function renderExclusions(): string {
	const audit = readAudit();
	if (!audit) return "";
	const lines: string[] = [];
	for (const provider of audit.providers ?? []) {
		const bad = (provider.models ?? []).filter((m) => m.state !== "ok");
		if (bad.length === 0) continue;
		lines.push(` * verified-${provider.id}:`);
		for (const m of bad) lines.push(` *   ${m.id}: ${m.state} — ${m.detail ?? ""}`);
	}
	if (lines.length === 0) return "";
	return ["/*", " * Excluded during the audit — reachable but not usable as an agent model.", " *", ...lines, " */", ""].join("\n");
}

/** Write every registered `verified-*` provider to the opencode export. */
function writeOpencode(): void {
	if (OPENCODE_REGISTRY.size === 0) return;
	try {
		const provider: Record<string, unknown> = {};
		for (const [id, entry] of OPENCODE_REGISTRY) {
			if (entry.models.length === 0) continue;
			provider[id] = renderProvider(entry.models, entry.label, entry.baseUrl);
		}
		if (Object.keys(provider).length === 0) return;

		const doc = {
			$comment: OPENCODE_COMMENT,
			generatedAt: new Date().toISOString(),
			provider,
		};
		// JSONC: a trailing block comment records what the audit excluded, which
		// is the part people otherwise re-investigate by hand. Strict JSON
		// parsers reject it, so anything piping this file must strip it.
		const excluded = renderExclusions();
		const tmp = `${OPENCODE_PATH}.${process.pid}.tmp`;
		writeFileSync(tmp, `${JSON.stringify(doc, null, 2)}\n${excluded}`, "utf-8");
		renameSync(tmp, OPENCODE_PATH);
		report(`opencode export: ${Object.keys(provider).length} provider(s) written`);
	} catch (error) {
		report(`could not write opencode export: ${errorMessage(error)}`);
	}
}

// ---------------------------------------------------------------------------
// Network
// ---------------------------------------------------------------------------

function errorMessage(error: unknown): string {
	return error instanceof Error ? error.message : String(error);
}

let logSink: ((message: string) => void) | undefined;
function report(message: string): void {
	if (logSink) logSink(message);
}

async function fetchCatalog(baseUrl: string, apiKey: string, timeoutMs: number): Promise<WireModel[]> {
	const controller = new AbortController();
	const timer = setTimeout(() => controller.abort(), timeoutMs);
	try {
		const response = await fetch(`${baseUrl}/models`, {
			headers: { Authorization: `Bearer ${apiKey}` },
			signal: controller.signal,
		});
		if (!response.ok) throw new Error(`HTTP ${response.status}`);
		const body = (await response.json()) as { data?: WireModel[] };
		if (!Array.isArray(body.data)) throw new Error("malformed catalog: no data array");
		return body.data;
	} finally {
		clearTimeout(timer);
	}
}

/**
 * One-token completion confirming a listed model is actually reachable.
 * Catalog presence is not availability: a free model can stay listed while the
 * proxy answers 404 (retired) or 429 (upstream at capacity).
 */
async function probeModel(
	model: WireModel,
	baseUrl: string,
	apiKey: string,
	config: HermesConfig,
): Promise<ProbeResult> {
	const checkedAt = new Date().toISOString();
	const controller = new AbortController();
	const timer = setTimeout(() => controller.abort(), config.probeTimeoutMs);
	try {
		const response = await fetch(`${baseUrl}/chat/completions`, {
			method: "POST",
			headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
			body: JSON.stringify({
				model: model.id,
				messages: [{ role: "user", content: "hi" }],
				max_tokens: config.probeMaxTokens,
				stream: false,
			}),
			signal: controller.signal,
		});
		if (response.ok) return { status: response.status, ok: true, checkedAt };
		const detail = (await response.text()).slice(0, 200);
		return { status: response.status, ok: false, checkedAt, detail };
	} catch (error) {
		return { status: "error", ok: false, checkedAt, detail: errorMessage(error).slice(0, 200) };
	} finally {
		clearTimeout(timer);
	}
}

async function runProbes(
	models: WireModel[],
	baseUrl: string,
	apiKey: string,
	config: HermesConfig,
): Promise<Record<string, ProbeResult>> {
	const results: Record<string, ProbeResult> = {};
	const limit = Math.max(1, config.probeConcurrency);
	let cursor = 0;

	async function worker(): Promise<void> {
		while (cursor < models.length) {
			const model = models[cursor++];
			if (!model?.id) continue;
			results[model.id] = await probeModel(model, baseUrl, apiKey, config);
		}
	}

	await Promise.all(Array.from({ length: Math.min(limit, models.length) }, worker));
	return results;
}

// ---------------------------------------------------------------------------
// Load pipeline
// ---------------------------------------------------------------------------

interface LoadResult {
	models: ProviderModelConfig[];
	source: CacheFile["source"];
	catalogTotal: number;
	generatedAt?: string;
	probes?: Record<string, ProbeResult>;
	note?: string;
}

async function loadCatalog(config: HermesConfig, allowNetwork: boolean): Promise<LoadResult> {
	let source: CacheFile["source"] = "seed";
	let catalogTotal = 0;
	let note: string | undefined;

	if (allowNetwork) {
		try {
			const catalog = await fetchCatalog(config.baseUrl, config.apiKey, config.fetchTimeoutMs);
			catalogTotal = catalog.length;
			const selection = selectModels(catalog, config);
			if (selection.models.length >= config.minModelsToAccept) {
				const generatedAt = new Date().toISOString();
				let probes: Record<string, ProbeResult> | undefined;
				if (config.verifyProbe !== "off") {
					const targets =
						config.verifyProbe === "all" ? selection.wire : selection.wire.filter(isFree);
					probes = await runProbes(targets, config.baseUrl, config.apiKey, config);
				}
				writeCache({
					version: 1,
					generatedAt,
					source: "proxy",
					baseUrl: config.baseUrl,
					catalogTotal,
					selectedTotal: selection.wire.length,
					catalog: selection.wire,
					probes,
				});
				// The opencode export is driven by what actually registers, not by
				// this one provider's result. Record here, write once at the end.
				OPENCODE_REGISTRY.set(PROVIDER_ID, {
					label: "Hermes Proxy (verified)",
					baseUrl: config.baseUrl,
					models: selection.models,
				});
				writeOpencode();
				return {
					models: selection.models,
					source: "proxy",
					catalogTotal,
					generatedAt,
					probes,
					note,
				};
			}
			note = `proxy returned ${selection.models.length} usable models, below minimum ${config.minModelsToAccept}`;
		} catch (error) {
			note = `proxy unreachable: ${errorMessage(error)}`;
		}
	}

	const cache = readCache();
	if (cache && cache.catalog.length > 0) {
		const selection = selectModels(cache.catalog, config);
		if (selection.models.length >= config.minModelsToAccept) {
			report(`verified-hermes: using cache from ${cache.generatedAt} (${note ?? "no network"})`);
			return {
				models: selection.models,
				source: "cache",
				catalogTotal: cache.catalogTotal,
				generatedAt: cache.generatedAt,
				probes: cache.probes,
				note,
			};
		}
		note = `${note ?? "cache unusable"}; cache had ${selection.models.length} usable models`;
	}

	const seed = readSeed();
	const seedSelection = selectModels(seed, config);
	if (seedSelection.models.length === 0) {
		report(`verified-hermes: no models available (${note ?? "all sources empty"})`);
		return { models: [], source: "seed", catalogTotal: 0, note };
	}
	report(`verified-hermes: falling back to seed models.json (${note ?? "no network, no cache"})`);
	return { models: seedSelection.models, source: "seed", catalogTotal: seed.length, note };
}

